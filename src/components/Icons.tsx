// Pixel-grid icons drawn on an 8×8 grid. Each string row is one pixel row.
const ICONS = {
  doc: ["01111100", "01000110", "01000010", "01011010", "01000010", "01011010", "01000010", "01111110"],
  scale: ["00011000", "11111111", "10011001", "10011001", "11011011", "00011000", "00011000", "00111100"],
  clock: ["00111100", "01000010", "10001001", "10001001", "10011001", "10000001", "01000010", "00111100"],
  graph: ["11000011", "11000011", "00100100", "00011000", "00011000", "00100100", "11000011", "11000011"],
  search: ["00111000", "01000100", "10000010", "10000010", "01000100", "00111100", "00000110", "00000011"],
  flag: ["11111100", "10000110", "10000011", "10000110", "11111100", "10000000", "10000000", "10000000"],
  spark: ["00010000", "00010000", "01010100", "00111000", "11111110", "00111000", "01010100", "00010000"],
  check: ["00000000", "00000011", "00000110", "00001100", "11011000", "01110000", "00100000", "00000000"],
  arrow: ["00000000", "00011000", "00001100", "11111110", "11111110", "00001100", "00011000", "00000000"],
} as const;

export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, size = 16, className = "" }: { name: IconName; size?: number; className?: string }) {
  const rows = ICONS[name];
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" className={className} aria-hidden="true" shapeRendering="crispEdges">
      {rows.flatMap((row, y) =>
        [...row].map((c, x) => (c === "1" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" /> : null)),
      )}
    </svg>
  );
}
