"use client";

import Link from "next/link";
import { useState } from "react";
import { StatusBadge } from "./StatusBadge";

interface Result {
  decomposition: null | {
    checkable: boolean;
    normalizedProposition: string;
    kind: string;
    splitInto: { proposition: string; kind: string }[];
    questions: string[];
    evidenceNeeded: string[];
    ambiguities: string[];
  };
  related: { slug: string; code: string; headline: string; status: "WIDELY_AGREED" | "DISPUTED" | "UNVERIFIED"; topic: string }[];
  aiEnabled?: boolean;
  error?: string;
}

const KIND: Record<string, string> = { FACTUAL: "Did it happen?", CAUSAL: "What caused it?", RESPONSIBILITY: "Who is responsible?", LEGAL: "What does the law say?", VALUE: "Was it justified? (value judgement)" };

export function Decomposer({ signedIn, aiEnabled, initialText }: { signedIn: boolean; aiEnabled: boolean; initialText: string }) {
  const [text, setText] = useState(initialText);
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<Result | null>(null);

  async function run(e: React.FormEvent) {
    e.preventDefault();
    setLoading(true);
    setResult(null);
    const res = await fetch("/api/decompose", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ text }) });
    setResult(await res.json().catch(() => ({ decomposition: null, related: [], error: "Something went wrong." })));
    setLoading(false);
  }

  if (!signedIn) {
    return <p className="panel p-5"><a href="/login?next=/decompose" className="text-accent">Sign in</a> to use the claim checker. Signing in lets us rate-limit the tool fairly.</p>;
  }

  const d = result?.decomposition;
  return (
    <div>
      <form onSubmit={run} className="grid gap-3">
        <label htmlFor="claim" className="label">Claim</label>
        <textarea id="claim" className="input min-h-32 text-lg" value={text} onChange={(e) => setText(e.target.value)} minLength={10} maxLength={2000} required placeholder="e.g. “The government changed the official election results.”" />
        <div className="flex items-center gap-3">
          <button className="btn-primary" disabled={loading}>{loading ? "Analysing…" : "Break it down"}</button>
          {!aiEnabled && <span className="text-xs text-muted">AI decomposition is not configured on this server; we will still search existing dossiers.</span>}
        </div>
      </form>

      {result?.error && <p className="mt-6 text-danger">{result.error}</p>}

      {result && result.related.length > 0 && (
        <section className="mt-10">
          <h2 className="label">Related dossiers we have published</h2>
          <ul className="mt-3 space-y-2">
            {result.related.map((r) => (
              <li key={r.slug} className="panel flex flex-wrap items-center justify-between gap-3 p-4">
                <Link href={`/claims/${r.slug}`}>{r.code} — {r.headline}</Link>
                <StatusBadge status={r.status} />
              </li>
            ))}
          </ul>
        </section>
      )}

      {d && (
        <section className="mt-10 space-y-8">
          <div className="border-l-2 border-accent pl-4">
            <p className="label">Most precise testable version</p>
            <p className="mt-1 text-xl">{d.normalizedProposition}</p>
            <p className="label mt-2">{KIND[d.kind] ?? d.kind}{!d.checkable && " · mostly a value judgement"}</p>
          </div>
          {d.splitInto.length > 1 && (
            <div>
              <h3 className="label">This bundles separate claims</h3>
              <ul className="mt-2 list-disc space-y-1 pl-5">{d.splitInto.map((s) => <li key={s.proposition}>{s.proposition} <span className="text-xs text-muted">({KIND[s.kind] ?? s.kind})</span></li>)}</ul>
            </div>
          )}
          <div>
            <h3 className="label">Questions to answer</h3>
            <ol className="mt-2 list-decimal space-y-1 pl-5">{d.questions.map((q) => <li key={q}>{q}</li>)}</ol>
          </div>
          <div>
            <h3 className="label">Evidence that would settle it</h3>
            <ul className="mt-2 list-disc space-y-1 pl-5">{d.evidenceNeeded.map((q) => <li key={q}>{q}</li>)}</ul>
          </div>
          {d.ambiguities.length > 0 && (
            <div>
              <h3 className="label">Vague or loaded terms to pin down</h3>
              <ul className="mt-2 list-disc space-y-1 pl-5 text-disputed">{d.ambiguities.map((q) => <li key={q}>{q}</li>)}</ul>
            </div>
          )}
          <p className="text-xs text-muted">Generated by an AI model to structure the question. It contains no evidence assessment. Want us to investigate? Use the challenge form on any topic page.</p>
        </section>
      )}
    </div>
  );
}
